function query(context, example) {
  if (!context.query) throw new Error(`Enter a value. Example: ${context.prefix}${example}`);
  return context.query.slice(0, 500);
}

async function sourceImage(context) {
  const target = mediaMessage(context.details);
  const type = getContentType(unwrapMessage(target?.message));
  if (!["imageMessage", "stickerMessage"].includes(type)) {
    throw new Error("Send or reply to an image or sticker.");
  }
  return downloadMedia(context.socket, target, context.config.maxMediaBytes);
}

function fancyText(value) {
  const normal = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789";
  const styled = "𝒂𝒃𝒄𝒅𝒆𝒇𝒈𝒉𝒊𝒋𝒌𝒍𝒎𝒏𝒐𝒑𝒒𝒓𝒔𝒕𝒖𝒗𝒘𝒙𝒚𝒛𝑨𝑩𝑪𝑫𝑬𝑭𝑮𝑯𝑰𝑱𝑲𝑳𝑴𝑵𝑶𝑷𝑸𝑹𝑺𝑻𝑼𝑽𝑾𝑿𝒀𝒁0123456789";
  const characters = [...styled];
  return [...value].map((character) => {
    const index = normal.indexOf(character);
    return index >= 0 ? characters[index] : character;
  }).join("");
}

